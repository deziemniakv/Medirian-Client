const dictionaries = { en, pl };

export function translate(language: 'en' | 'pl', key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[language][key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function useT(): (key: MessageKey, vars?: Record<string, string | number>) => string {
  const language = useStore((s) => s.settings?.language ?? 'en');
  return (key, vars) => translate(language, key, vars);
}
