export type IconName = keyof typeof MAPS;

const RECTS: Record<string, JSX.Element[]> = {};

/** Merges each row's runs of pixels into rectangles. */
function rects(name: IconName): JSX.Element[] {
  if (!RECTS[name]) {
    const out: JSX.Element[] = [];
    MAPS[name].forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        const start = x;
        while (x < row.length && row[x] === '#') {
          x++;
        }
        out.push(<rect key={`${y}-${start}`} x={start} y={y} width={x - start} height={1} />);
      }
    });
    RECTS[name] = out;
  }
  return RECTS[name];
}

export function Icon({ name, size = 16, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg className={`icon${className ? ` ${className}` : ''}`} width={size} height={size} viewBox="0 0 8 8"
      shapeRendering="crispEdges" fill="currentColor" aria-hidden="true">
      {rects(name)}
    </svg>
  );
}

const ART = import.meta.glob('../../assets/icons/*.png', { eager: true, import: 'default' }) as Record<string, string>;

/** One of the colourful 16×16 Medirian icons (the same art as in the game), at {@code scale}× size. */
export function ArtIcon({ name, scale = 2, className }: { name: string; scale?: number; className?: string }) {
  const src = ART[`../../assets/icons/${name}.png`];
  if (!src) {
    return null;
  }
  return <img className={`art-icon${className ? ` ${className}` : ''}`} src={src} width={16 * scale} height={16 * scale} alt="" draggable={false} />;
}
